create or replace function public.operar_inventario(
  p_medicamento_id bigint,
  p_tipo text,
  p_cantidad integer,
  p_usuario text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  producto medicamentos%rowtype;
  actividad actividades%rowtype;
  cantidad_resultante integer;
begin
  if p_tipo not in ('baja', 'salida', 'ajuste') then
    raise exception 'Operación inválida';
  end if;

  select * into producto from medicamentos where id = p_medicamento_id for update;
  if not found then
    raise exception 'Producto no encontrado';
  end if;

  if p_tipo = 'salida' then
    if p_cantidad is null or p_cantidad < 1 then raise exception 'La cantidad de salida debe ser mayor que cero'; end if;
    if p_cantidad > producto.cantidad then raise exception 'La cantidad de salida supera el stock disponible'; end if;
    cantidad_resultante := producto.cantidad - p_cantidad;
  elsif p_tipo = 'ajuste' then
    if p_cantidad is null or p_cantidad < 0 then raise exception 'La cantidad ajustada no puede ser negativa'; end if;
    cantidad_resultante := p_cantidad;
  else
    if producto.cantidad < 1 then raise exception 'El producto no tiene stock disponible'; end if;
    cantidad_resultante := 0;
  end if;

  update medicamentos set cantidad = cantidad_resultante, updated_at = now()
  where id = producto.id returning * into producto;

  insert into actividades (tipo, medicamento_id, medicamento, cantidad, descripcion, fecha, usuario)
  values (
    p_tipo, producto.id, producto.nombre,
    case when p_tipo = 'baja' then 0 else p_cantidad end,
    case p_tipo when 'salida' then 'Salida de inventario: ' when 'ajuste' then 'Ajuste de inventario: ' else 'Baja de inventario: ' end || producto.nombre,
    now(), p_usuario
  ) returning * into actividad;

  return jsonb_build_object('medicamento', to_jsonb(producto), 'actividad', to_jsonb(actividad));
end;
$$;

revoke all on function public.operar_inventario(bigint, text, integer, text) from public;
grant execute on function public.operar_inventario(bigint, text, integer, text) to service_role;
