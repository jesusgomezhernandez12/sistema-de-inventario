create table if not exists public.medicamentos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  tipo text not null check (tipo in ('medicamento', 'vacuna')),
  presentacion text not null default '',
  concentracion text not null default '',
  cantidad integer not null default 1 check (cantidad >= 0),
  unidad text not null default 'frascos',
  fecha_caducidad date not null,
  fecha_ingreso date not null default current_date,
  observaciones text not null default '',
  imagen_url text not null default '',
  requiere_receta boolean not null default false,
  es_controlado boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.actividades (
  id bigint generated by default as identity primary key,
  tipo text not null check (tipo in ('entrada', 'salida', 'ajuste', 'caducidad', 'baja')),
  medicamento_id bigint references public.medicamentos(id) on delete set null,
  medicamento text not null default '',
  lote text not null default '',
  cantidad integer,
  descripcion text not null,
  fecha timestamptz not null default now(),
  usuario text not null default 'Sistema',
  created_at timestamptz not null default now()
);

create table if not exists public.usuarios (
  id bigint generated by default as identity primary key,
  nombre text not null,
  email text not null unique,
  password text not null,
  rol text not null default 'visualizador' check (rol in ('admin', 'veterinario', 'tecnico', 'visualizador')),
  activo boolean not null default true,
  ultimo_acceso timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

